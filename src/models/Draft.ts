import {
  agentSessionPath,
  commentPath,
  initiativeActivityPath,
  initiativeUpdateDraftPath,
  issuePath,
  projectUpdateDraftPath,
  projectUpdatesPath,
  reviewChangesPath,
  reviewCommentPath,
  reviewPath,
  updateOnUpdatesPagePath,
} from "#utils/urls";
